-- TradeIntel AI managed PostgreSQL schema.
-- This migration is for a NEW database only. It does not read, alter, or delete Supabase data.
-- Execute through the migration runner so schema_migrations is updated transactionally.

CREATE TABLE IF NOT EXISTS schema_migrations (
  version text PRIMARY KEY,
  checksum text NOT NULL,
  applied_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS datasets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  filename text NOT NULL,
  file_type text NOT NULL,
  content_hash text,
  storage_key text,
  original_size_bytes bigint CHECK (original_size_bytes IS NULL OR original_size_bytes >= 0),
  uploaded_at timestamptz,
  total_rows bigint NOT NULL DEFAULT 0 CHECK (total_rows >= 0),
  valid_rows bigint NOT NULL DEFAULT 0 CHECK (valid_rows >= 0),
  duplicate_rows bigint NOT NULL DEFAULT 0 CHECK (duplicate_rows >= 0),
  error_rows bigint NOT NULL DEFAULT 0 CHECK (error_rows >= 0),
  column_mapping jsonb NOT NULL DEFAULT '{}'::jsonb,
  detected_entities jsonb NOT NULL DEFAULT '{}'::jsonb,
  status text NOT NULL DEFAULT 'QUEUED',
  import_status text NOT NULL DEFAULT 'QUEUED'
    CHECK (import_status IN ('QUEUED','RUNNING','COMPLETED','FAILED','BLOCKED','REVIEW_REQUIRED')),
  analysis_status text NOT NULL DEFAULT 'QUEUED'
    CHECK (analysis_status IN ('QUEUED','RUNNING','COMPLETED','FAILED','BLOCKED','REVIEW_REQUIRED')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  import_completed_at timestamptz,
  analysis_completed_at timestamptz,
  retained_at timestamptz,
  CHECK (valid_rows + duplicate_rows + error_rows <= total_rows)
);

CREATE INDEX IF NOT EXISTS datasets_status_created_idx ON datasets (status, created_at DESC);
CREATE INDEX IF NOT EXISTS datasets_analysis_created_idx ON datasets (analysis_status, analysis_completed_at DESC NULLS LAST);
CREATE UNIQUE INDEX IF NOT EXISTS datasets_content_hash_uq ON datasets (content_hash) WHERE content_hash IS NOT NULL;

CREATE TABLE IF NOT EXISTS raw_records (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dataset_id bigint NOT NULL REFERENCES datasets(id) ON DELETE RESTRICT,
  row_index bigint NOT NULL CHECK (row_index > 0),
  raw_data jsonb NOT NULL,
  errors jsonb NOT NULL DEFAULT '[]'::jsonb,
  is_valid boolean NOT NULL,
  is_duplicate boolean NOT NULL DEFAULT false,
  duplicate_of_row_index bigint,
  raw_hash text,
  CHECK (NOT is_duplicate OR is_valid),
  CHECK (duplicate_of_row_index IS NULL OR duplicate_of_row_index > 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (dataset_id, row_index)
);

CREATE INDEX IF NOT EXISTS raw_records_dataset_id_idx ON raw_records (dataset_id, id);
CREATE INDEX IF NOT EXISTS raw_records_dataset_valid_idx ON raw_records (dataset_id, is_valid, id);
CREATE INDEX IF NOT EXISTS raw_records_dataset_hash_idx ON raw_records (dataset_id, raw_hash) WHERE raw_hash IS NOT NULL;

CREATE TABLE IF NOT EXISTS companies (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dataset_id bigint NOT NULL REFERENCES datasets(id) ON DELETE RESTRICT,
  name text NOT NULL,
  normalized_name text NOT NULL,
  country text,
  industry text,
  primary_products text[] NOT NULL DEFAULT ARRAY[]::text[],
  total_transactions bigint NOT NULL DEFAULT 0 CHECK (total_transactions >= 0),
  total_value numeric(24,4) NOT NULL DEFAULT 0,
  last_activity_date timestamptz,
  roles text[] NOT NULL DEFAULT ARRAY[]::text[],
  status text NOT NULL DEFAULT 'ACTIVE',
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (dataset_id, id),
  UNIQUE (dataset_id, normalized_name)
);

CREATE INDEX IF NOT EXISTS companies_dataset_id_idx ON companies (dataset_id, id);
CREATE INDEX IF NOT EXISTS companies_dataset_value_idx ON companies (dataset_id, total_value DESC);

CREATE TABLE IF NOT EXISTS products (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dataset_id bigint NOT NULL REFERENCES datasets(id) ON DELETE RESTRICT,
  name text NOT NULL,
  normalized_name text NOT NULL,
  category text NOT NULL DEFAULT 'Trade',
  hs_code text,
  total_demand_qty numeric(24,4) NOT NULL DEFAULT 0,
  total_demand_val numeric(24,4) NOT NULL DEFAULT 0,
  frequency bigint NOT NULL DEFAULT 0 CHECK (frequency >= 0),
  top_markets text[] NOT NULL DEFAULT ARRAY[]::text[],
  top_buyers text[] NOT NULL DEFAULT ARRAY[]::text[],
  top_suppliers text[] NOT NULL DEFAULT ARRAY[]::text[],
  growth_trend jsonb,
  recency_date timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (dataset_id, id),
  UNIQUE (dataset_id, normalized_name, category)
);

CREATE INDEX IF NOT EXISTS products_dataset_id_idx ON products (dataset_id, id);
CREATE INDEX IF NOT EXISTS products_dataset_frequency_idx ON products (dataset_id, frequency DESC);

CREATE TABLE IF NOT EXISTS markets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dataset_id bigint NOT NULL REFERENCES datasets(id) ON DELETE RESTRICT,
  country text NOT NULL,
  normalized_country text NOT NULL,
  region text,
  active_companies_count bigint NOT NULL DEFAULT 0 CHECK (active_companies_count >= 0),
  top_demanded_products text[] NOT NULL DEFAULT ARRAY[]::text[],
  total_trade_volume numeric(24,4) NOT NULL DEFAULT 0,
  market_gaps jsonb NOT NULL DEFAULT '[]'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (dataset_id, id),
  UNIQUE (dataset_id, normalized_country)
);

CREATE INDEX IF NOT EXISTS markets_dataset_id_idx ON markets (dataset_id, id);
CREATE INDEX IF NOT EXISTS markets_dataset_volume_idx ON markets (dataset_id, total_trade_volume DESC);

CREATE TABLE IF NOT EXISTS normalized_records (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dataset_id bigint NOT NULL REFERENCES datasets(id) ON DELETE RESTRICT,
  source_row_index bigint NOT NULL CHECK (source_row_index > 0),
  source_hash text NOT NULL,
  company_id bigint,
  product_id bigint,
  market_id bigint,
  company_name text NOT NULL,
  product_name text NOT NULL,
  category text NOT NULL DEFAULT 'Trade',
  role text NOT NULL DEFAULT 'buyer',
  country text NOT NULL DEFAULT 'Unknown',
  quantity numeric(24,4) NOT NULL DEFAULT 0,
  unit text NOT NULL DEFAULT 'Units',
  value_amount numeric(24,4) NOT NULL DEFAULT 0,
  currency text NOT NULL DEFAULT 'INR',
  transaction_date date,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (dataset_id, source_hash),
  UNIQUE (dataset_id, id),
  FOREIGN KEY (dataset_id, company_id) REFERENCES companies(dataset_id, id) ON DELETE RESTRICT,
  FOREIGN KEY (dataset_id, product_id) REFERENCES products(dataset_id, id) ON DELETE RESTRICT,
  FOREIGN KEY (dataset_id, market_id) REFERENCES markets(dataset_id, id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS normalized_records_dataset_id_idx ON normalized_records (dataset_id, id);
CREATE INDEX IF NOT EXISTS normalized_records_dataset_company_idx ON normalized_records (dataset_id, company_id, id);
CREATE INDEX IF NOT EXISTS normalized_records_dataset_product_idx ON normalized_records (dataset_id, product_id, id);
CREATE INDEX IF NOT EXISTS normalized_records_dataset_name_idx ON normalized_records (dataset_id, company_name, product_name);

CREATE TABLE IF NOT EXISTS company_potential (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dataset_id bigint NOT NULL REFERENCES datasets(id) ON DELETE RESTRICT,
  company_id bigint NOT NULL,
  total_score numeric(5,2) NOT NULL CHECK (total_score >= 0 AND total_score <= 100),
  category text NOT NULL,
  product_fit_score numeric(5,2) NOT NULL DEFAULT 0,
  activity_score numeric(5,2) NOT NULL DEFAULT 0,
  recency_score numeric(5,2) NOT NULL DEFAULT 0,
  market_fit_score numeric(5,2) NOT NULL DEFAULT 0,
  commercial_relevance_score numeric(5,2) NOT NULL DEFAULT 0,
  growth_score numeric(5,2) NOT NULL DEFAULT 0,
  supplier_diversification_score numeric(5,2) NOT NULL DEFAULT 0,
  engagement_score numeric(5,2) NOT NULL DEFAULT 0,
  confidence numeric(5,4),
  evidence_breakdown jsonb NOT NULL DEFAULT '{}'::jsonb,
  calculated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (dataset_id, company_id),
  FOREIGN KEY (dataset_id, company_id) REFERENCES companies(dataset_id, id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS company_potential_dataset_score_idx ON company_potential (dataset_id, total_score DESC);
CREATE INDEX IF NOT EXISTS company_potential_dataset_category_idx ON company_potential (dataset_id, category, total_score DESC);

CREATE TABLE IF NOT EXISTS contacts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dataset_id bigint,
  company_id bigint,
  name text,
  role text,
  email text,
  source text,
  source_url text,
  verification_status text NOT NULL DEFAULT 'UNVERIFIED',
  confidence numeric(5,4),
  is_suppressed boolean NOT NULL DEFAULT false,
  suppression_reason text,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (dataset_id, id),
  FOREIGN KEY (dataset_id) REFERENCES datasets(id) ON DELETE RESTRICT,
  FOREIGN KEY (dataset_id, company_id) REFERENCES companies(dataset_id, id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS contacts_dataset_company_idx ON contacts (dataset_id, company_id);
CREATE INDEX IF NOT EXISTS contacts_company_email_idx ON contacts (company_id, lower(email)) WHERE email IS NOT NULL;
CREATE INDEX IF NOT EXISTS contacts_suppression_verification_idx ON contacts (is_suppressed, verification_status);

CREATE TABLE IF NOT EXISTS web_research (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dataset_id bigint,
  company_id bigint,
  provider text,
  query text,
  source_url text,
  result jsonb NOT NULL DEFAULT '{}'::jsonb,
  researched_at timestamptz NOT NULL DEFAULT now(),
  FOREIGN KEY (dataset_id) REFERENCES datasets(id) ON DELETE RESTRICT,
  FOREIGN KEY (dataset_id, company_id) REFERENCES companies(dataset_id, id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS web_research_dataset_company_idx ON web_research (dataset_id, company_id, researched_at DESC);
CREATE INDEX IF NOT EXISTS web_research_researched_at_idx ON web_research (researched_at DESC);

CREATE TABLE IF NOT EXISTS leads (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dataset_id bigint NOT NULL REFERENCES datasets(id) ON DELETE RESTRICT,
  company_id bigint NOT NULL,
  contact_id bigint,
  dedup_key text,
  company_name text NOT NULL,
  contact_name text,
  product_requirement text NOT NULL DEFAULT '',
  intent_type text NOT NULL,
  evidence jsonb NOT NULL DEFAULT '{}'::jsonb,
  score numeric(5,2) NOT NULL DEFAULT 0,
  confidence numeric(5,4),
  recommended_human_action text,
  status text NOT NULL DEFAULT 'NEW',
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (dataset_id, id),
  FOREIGN KEY (dataset_id, company_id) REFERENCES companies(dataset_id, id) ON DELETE RESTRICT,
  FOREIGN KEY (dataset_id, contact_id) REFERENCES contacts(dataset_id, id) ON DELETE RESTRICT
);

CREATE UNIQUE INDEX IF NOT EXISTS leads_potential_dedup_uq
  ON leads (dataset_id, company_id, intent_type)
  WHERE intent_type = 'COMPANY_POTENTIAL';
CREATE UNIQUE INDEX IF NOT EXISTS leads_dataset_dedup_key_uq
  ON leads (dataset_id, dedup_key)
  WHERE dedup_key IS NOT NULL;
CREATE INDEX IF NOT EXISTS leads_dataset_status_created_idx ON leads (dataset_id, status, created_at DESC);
CREATE INDEX IF NOT EXISTS leads_dataset_company_idx ON leads (dataset_id, company_id);
CREATE INDEX IF NOT EXISTS leads_score_idx ON leads (score DESC);

